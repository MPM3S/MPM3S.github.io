"""Write the generated parts of plough_setup.tex:
  plough_triangles.tex - the plough, read from the MPM3S STL file and drawn as shaded triangles in the
                         oblique view;
  plough_points.tex    - the coordinates of the share tip, its path (end of stage 2, end of the drawn
                         stage 3), two label points, and the x of the two boundary-track planes;
  plough_gimps.tex     - the GIMP domains of the active window of soil, back to front.

The plough is placed as at the start of stage 2: moved 5 m in +x ("offset") and lowered onto the soil
surface. Lengths are in units of 6.4 m, the schematic element of plough_setup.tex (two of the real 3.2 m
base elements). The track planes are drawn where MPM3S puts them: 5 m behind and 10 m ahead of the
plough, rounded outward to whole 3.2 m base elements.
Run:  python3 plough_triangles.py path/to/MPM3S/validation_data_and_jsons
"""
import struct, sys, pathlib, math
import numpy as np

unit = 6.4                      # m per drawing unit (one schematic element)
base = 3.2                      # m, the real base element (the 5 m requested, rounded to 0.05 x 2^6)
surface = 2.0                   # soil surface in drawing units (two element layers drawn)
offset = np.array([5.0, 0.0, 0.0])
depth, L = 1.85, 7.9286          # final depth and plough length (m)
view = np.array([1.0, -2.0, 0.8]) / np.linalg.norm([1.0, -2.0, 0.8])   # towards the viewer
light = np.array([0.4, -0.5, 1.0]) / np.linalg.norm([0.4, -0.5, 1.0])

def triangles(path):
    raw = pathlib.Path(path).read_bytes()
    if raw[:5] == b"solid" and b"facet" in raw[:300]:
        v = [list(map(float, l.split()[1:4])) for l in raw.decode().splitlines() if l.strip().startswith("vertex")]
        return np.array(v).reshape(-1, 3, 3)
    n = struct.unpack("<I", raw[80:84])[0]
    rec = np.frombuffer(raw[84:84 + 50 * n], dtype=np.dtype([("n", "<3f4"), ("v", "<9f4"), ("a", "<u2")]))
    return rec["v"].reshape(-1, 3, 3).astype(float)

folder = pathlib.Path(sys.argv[1])
tris = triangles(folder / "plough.stl")
zmin = tris[..., 2].min()
draw = lambda p: (np.asarray(p) + offset) / unit + np.array([0, 0, surface - zmin / unit])

faces = []
for t in draw(tris):
    n = np.cross(t[1] - t[0], t[2] - t[0])
    if np.linalg.norm(n) == 0: continue
    n /= np.linalg.norm(n)
    if n @ view <= 0: continue                    # facing away from the viewer
    shade = 0.35 + 0.65 * max(0.0, n @ light)
    faces.append((t.mean(0) @ view, shade, t))
faces.sort(key=lambda f: f[0])                    # far to near
out = ["% generated by plough_triangles.py from plough.stl - do not edit"]
for _, shade, t in faces:
    pct = int(round(10 + 35 * (1 - shade)))       # darker red where the face turns from the light
    pts = " -- ".join(f"({x:.4f},{y:.4f},{z:.4f})" for x, y, z in t)
    out.append(f"\\filldraw[fill=rigidred!{pct}!white, draw=black, line width=0.12pt, line join=round] {pts} -- cycle;")
pathlib.Path(__file__).with_name("plough_triangles.tex").write_text("\n".join(out) + "\n")

v = tris.reshape(-1, 3)
low = v[v[:, 2] < zmin + 1e-6]
tip = low[low[:, 0].argmax()]                     # the share tip: the front-most node on the base
tip = np.array([tip[0], 0.0, tip[2]])             # on the plane of symmetry
blade = v[v[:, 2] > v[:, 2].max() - 1e-3]; blade = blade[blade[:, 0].argmin()]   # rear end of the top edge, for a label
share = v[(v[:, 0] > tip[0] - 0.6) & (v[:, 2] < zmin + 0.25)]; share = share[share[:, 1].argmin()]
end2 = tip + np.array([2 * L, 0.0, -depth])       # end of stage 2: 1.85 m down over two plough lengths
xmin, xmax = v[:, 0].min() + offset[0], v[:, 0].max() + offset[0]
trail = math.floor((xmin - 5.0) / base) * base     # 5 m behind, rounded outward to whole base elements
lead = math.ceil((xmax + 10.0) / base) * base      # 10 m ahead, likewise
out = ["% generated by plough_triangles.py from plough.stl - do not edit"]
for k, p in {"tip": tip, "end2": end2, "bladelabel": blade, "sharelabel": share}.items():
    x, y, z = draw(p); out.append(f"\\coordinate ({k}) at ({x:.4f},{y:.4f},{z:.4f});")
out.append(f"\\def\\pathz{{{draw(end2)[2]:.4f}}}   % height of the share tip in stage 3")
out.append(f"\\def\\trailx{{{trail / unit:.4f}}}   % boundary track: 5 m behind the plough, rounded to whole base elements")
out.append(f"\\def\\leadx{{{lead / unit:.4f}}}    % and 10 m ahead of it")
pathlib.Path(__file__).with_name("plough_points.tex").write_text("\n".join(out) + "\n")
print(len(faces), "faces written; plough spans x", round(xmin / unit, 3), "to", round(xmax / unit, 3),
      "units; track planes at", trail / unit, "and", lead / unit)

# --- the GIMP domains of the active window: elements x in [0, 4], y in [0, 2], z in [0, 2],
# 2 x 2 x 2 per element; the three elements the plough rests in (x in [0, 3], y in [0, 1], top
# layer) are refined once, so their GIMPs are half the size
refined = {(0, 0, 1), (1, 0, 1), (2, 0, 1)}
boxes = []
for ex in range(4):
    for ey in range(2):
        for ez in range(2):
            n = 4 if (ex, ey, ez) in refined else 2
            h = 1 / n
            for i in range(n):
                for j in range(n):
                    for k in range(n):
                        lo = np.array([ex + i * h, ey + j * h, ez + k * h])
                        boxes.append(((lo + h / 2) @ view, lo, h))
boxes.sort(key=lambda b: b[0])
gap = 0.025
out = ["% generated by plough_triangles.py - the GIMP domains of the active window, far to near - do not edit"]
for _, lo, h in boxes:
    x, y, z = lo + gap * h
    out.append(f"\\gimp{{{x:.4f}}}{{{y:.4f}}}{{{z:.4f}}}{{{h * (1 - 2 * gap):.4f}}}")
pathlib.Path(__file__).with_name("plough_gimps.tex").write_text("\n".join(out) + "\n")
print(len(boxes), "GIMP domains written")
