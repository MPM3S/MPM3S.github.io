"""Write input_builder_templates.js: the tutorials' complete input files, as starting points
for the interactive input builder (input_builder.js).
Run:  python3 make_input_builder_templates.py path/to/MPM3S/validation_data_and_jsons
"""
import json, pathlib, sys

TEMPLATES = [
    ("Tutorial 1 - Self-weight column", "input_data_gravity_column.json"),
    ("Tutorial 2 - Compaction via a rigid body", "input_data_compress.json"),
    ("Tutorial 3 - Vertical penetration (CPT)", "input_data_CPT_dr32.json"),
    ("Tutorial 5 - Rolling sphere", "input_data_sphere.json"),
    ("Tutorial 6 - Drag anchor", "input_data_AC14_dr32.json"),
]
folder = pathlib.Path(sys.argv[1])
data = [{"name": name, "file": f, "json": json.loads((folder / f).read_text())} for name, f in TEMPLATES]
out = ("// generated by make_input_builder_templates.py from MPM3S's validation_data_and_jsons - do not edit\n"
       "window.MPM3S_TEMPLATES = " + json.dumps(data, indent=1) + ";\n")
pathlib.Path(__file__).with_name("input_builder_templates.js").write_text(out)
print("wrote", len(data), "templates")
