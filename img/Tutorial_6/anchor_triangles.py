"""Write the generated parts of anchor_setup.tex:
  anchor_triangles.tex - the fluke and shank of the AC-14 anchor, read from the MPM3S STL
                         files and drawn as shaded triangles in the oblique view;
  anchor_gimps.tex     - the GIMP domains of the active window of soil, back to front.

The anchor is placed as at the start of stage 2: moved 1 m in +x ("offset") and lowered
onto the soil surface. Lengths are in units of the 3.2 m base element, the unit of
anchor_setup.tex.   Run:  python3 anchor_triangles.py path/to/MPM3S/validation_data_and_jsons
"""
import struct, sys, pathlib
import numpy as np

unit = 3.2                      # m per drawing unit (one base element)
surface = 2.0                   # soil surface in drawing units (two element layers drawn)
offset = np.array([1.0, 0.0, 0.0])
view = np.array([1.0, -2.0, 0.8]) / np.linalg.norm([1.0, -2.0, 0.8])   # towards the viewer
light = np.array([0.4, -0.5, 1.0]) / np.linalg.norm([0.4, -0.5, 1.0])

def triangles(path):
    raw = pathlib.Path(path).read_bytes()
    if raw[:5] == b"solid" and b"facet" in raw[:300]:
        v = [list(map(float, l.split()[1:4])) for l in raw.decode().splitlines() if l.strip().startswith("vertex")]
        return np.array(v).reshape(-1, 3, 3)
    n = struct.unpack("<I", raw[80:84])[0]
    rec = np.frombuffer(raw[84:84 + 50 * n], dtype=np.dtype([("n", "<3f4"), ("v", "<9f4"), ("a", "<u2")]))
    return rec["v"].reshape(-1, 3, 3).astype(float)

folder = pathlib.Path(sys.argv[1])
parts = {name: triangles(folder / f) for name, f in [("fluke", "fluke_round_nose.stl"), ("shank", "shank_scv2.stl")]}
zmin = min(t[..., 2].min() for t in parts.values())
faces = []
for name, tris in parts.items():
    p = (tris + offset) / unit
    p[..., 2] += surface - zmin / unit           # rest the lowest point on the surface
    for t in p:
        n = np.cross(t[1] - t[0], t[2] - t[0])
        if np.linalg.norm(n) == 0: continue
        n /= np.linalg.norm(n)
        if n @ view <= 0: continue                # facing away from the viewer
        shade = 0.35 + 0.65 * max(0.0, n @ light)
        faces.append((t.mean(0) @ view, shade, t))
faces.sort(key=lambda f: f[0])                    # far to near
out = ["% generated by anchor_triangles.py from fluke_round_nose.stl and shank_scv2.stl - do not edit"]
for _, shade, t in faces:
    pct = int(round(10 + 35 * (1 - shade)))       # darker red where the face turns from the light
    pts = " -- ".join(f"({x:.4f},{y:.4f},{z:.4f})" for x, y, z in t)
    out.append(f"\\filldraw[fill=rigidred!{pct}!white, draw=rigidred!{pct}!white, line width=0.1pt] {pts} -- cycle;")
pathlib.Path(__file__).with_name("anchor_triangles.tex").write_text("\n".join(out) + "\n")
print(len(faces), "faces written; anchor spans x", round(min(f[2][:, 0].min() for f in faces), 3), "to",
      round(max(f[2][:, 0].max() for f in faces), 3), "units")

# --- the GIMP domains of the active window: elements x in [0, 2], y in [0, 2], z in [0, 2],
# 2 x 2 x 2 per element; the two elements under the anchor (x in [0, 2], y in [0, 1], top
# layer) are refined once, so their GIMPs are half the size
refined = {(0, 0, 1), (1, 0, 1)}
boxes = []
for ex in range(2):
    for ey in range(2):
        for ez in range(2):
            n = 4 if (ex, ey, ez) in refined else 2
            h = 1 / n
            for i in range(n):
                for j in range(n):
                    for k in range(n):
                        lo = np.array([ex + i * h, ey + j * h, ez + k * h])
                        boxes.append(((lo + h / 2) @ view, lo, h))
boxes.sort(key=lambda b: b[0])
gap = 0.025
out = ["% generated by anchor_triangles.py - the GIMP domains of the active window, far to near - do not edit"]
for _, lo, h in boxes:
    x, y, z = lo + gap * h
    out.append(f"\\gimp{{{x:.4f}}}{{{y:.4f}}}{{{z:.4f}}}{{{h * (1 - 2 * gap):.4f}}}")
pathlib.Path(__file__).with_name("anchor_gimps.tex").write_text("\n".join(out) + "\n")
print(len(boxes), "GIMP domains written")
